/*
 * Regenerates `apps/web/src/utils/themeBase.ts` from the shipped token contract in
 * `packages/viviana-ui/src/viviana-tokens.css`.
 *
 * Theme Studio recolors *from* these maps, so a theme nobody has touched must reproduce
 * the library's own defaults exactly. Before this script the file was a hand-copied
 * snapshot with a comment asking the next person to keep it in sync — which is how it
 * ended up carrying the pre-Terminal-Glass ramp. `--check` makes the drift a gate
 * failure instead of a stale file.
 *
 * Dark  = the `:root, [data-color-scheme="dark"]` block.
 * Light = that block merged with `[data-color-scheme="light"]`, fully resolved, so the
 * map can be applied as inline custom properties inside a scoped preview.
 *
 * Only the `--color-*` compat ladder is emitted: `themeGen.ts` keys every family off
 * that prefix, and the register's own `--surface-*` / `--accent-*` tokens are not
 * knob-driven.
 */
import { promises as fs } from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const tokensPath = path.join(repoRoot, "packages/viviana-ui/src/viviana-tokens.css");
const outPath = path.join(repoRoot, "apps/web/src/utils/themeBase.ts");
const check = process.argv.includes("--check");

/** Strips comments so a `--color-*` mentioned in prose is never read as a declaration. */
function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

/** Declarations of one top-level rule whose selector list matches `test`. */
function blockFor(css, test) {
  const declarations = new Map();
  const rulePattern = /([^{}]+)\{([^{}]*)\}/g;
  let rule;
  while ((rule = rulePattern.exec(css))) {
    const selector = rule[1].trim().replace(/\s+/g, " ");
    if (!test(selector)) continue;
    for (const declaration of rule[2].split(";")) {
      const separator = declaration.indexOf(":");
      if (separator === -1) continue;
      const name = declaration.slice(0, separator).trim();
      if (!name.startsWith("--color-")) continue;
      declarations.set(name, declaration.slice(separator + 1).trim());
    }
  }
  return declarations;
}

function serialize(name, tokens) {
  const body = [...tokens]
    .map(([token, value]) => `  ${JSON.stringify(token)}: ${JSON.stringify(value)},`)
    .join("\n");
  return `export const ${name}: TokenMap = {\n${body}\n};`;
}

const css = stripComments(await fs.readFile(tokensPath, "utf8"));
const dark = blockFor(css, (selector) => /(^|,\s*):root($|,)/.test(selector));
const lightOverrides = blockFor(css, (selector) =>
  selector.includes('[data-color-scheme="light"]'),
);
if (dark.size === 0 || lightOverrides.size === 0) {
  throw new Error(`No --color-* declarations found in ${tokensPath}; the block selectors moved.`);
}
const light = new Map([...dark, ...lightOverrides]);

const source = `// AUTO-GENERATED by \`vp run generate:theme-base\` from
// packages/viviana-ui/src/viviana-tokens.css (the shipped /ui token contract).
// Do not edit by hand — \`vp run guard:theme-base\` fails when this drifts.
// These are the faithful default themes the Theme Studio recolors from; an untouched
// theme reproduces these exactly. Dark = :root defaults. Light = :root merged with the
// [data-color-scheme="light"] block (fully resolved, so it can be applied as inline
// custom properties in a scoped preview).

export type TokenMap = Record<string, string>;

${serialize("BASE_DARK", dark)}

${serialize("BASE_LIGHT", light)}
`;

const current = await fs.readFile(outPath, "utf8").catch(() => "");
if (current === source) {
  console.log(`themeBase.ts is up to date (${dark.size} dark / ${light.size} light tokens).`);
  process.exit(0);
}
if (check) {
  console.error(
    `themeBase.ts is stale against viviana-tokens.css. Run \`vp run generate:theme-base\`.`,
  );
  process.exit(1);
}
await fs.writeFile(outPath, source);
console.log(`Wrote themeBase.ts (${dark.size} dark / ${light.size} light tokens).`);
